#!/usr/bin/env python3
"""Compiles the Enhanced Graphics HLSL sources to D3D9 SM3 bytecode and writes
src/System/PC/PCEnhancedGraphicsShaders.inl.

Compiler: hlslc.exe (this folder) calling D3DCompile from d3dcompiler_47.dll.
On Windows it uses Microsoft's d3dcompiler_47; on Linux it runs under Wine,
whose d3dcompiler_47 is built on vkd3d-shader. Every shader is disassembled and
checked for the expected shader model before it is embedded.
"""
import hashlib, os, subprocess, sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
SRC = os.path.join(ROOT, "src", "System", "PC", "Shaders", "EnhancedGraphics")
OUT = os.path.join(ROOT, "src", "System", "PC", "PCEnhancedGraphicsShaders.inl")
HLSLC = os.environ.get("HLSLC", os.path.join(os.path.dirname(__file__), "hlslc.exe"))
RUNNER = [] if os.name == "nt" else ["wine"]

SHADERS = [
    ("g_EgFullscreenVS", "eg_fullscreen_vs.hlsl", "vs_3_0"),
    ("g_EgBrightPS",     "eg_bright_ps.hlsl",     "ps_3_0"),
    ("g_EgBlurPS",       "eg_blur_ps.hlsl",       "ps_3_0"),
    ("g_EgCompositePS",  "eg_composite_ps.hlsl",  "ps_3_0"),
    ("g_EgWaterVS",      "eg_water_vs.hlsl",      "vs_3_0"),
    ("g_EgWaterPS",      "eg_water_ps.hlsl",      "ps_3_0"),
]

def main():
    work = os.path.join(ROOT, "build", "eg_shaders")
    os.makedirs(work, exist_ok=True)
    out = ["/* Generated by tools/EnhancedGraphics/build_shaders.py - do not edit. */", ""]
    for sym, src, prof in SHADERS:
        b = os.path.join(work, src + ".bin"); a = os.path.join(work, src + ".asm")
        r = subprocess.run(RUNNER + [HLSLC, os.path.join(SRC, src), "main", prof, b, a],
                           capture_output=True, text=True, env=dict(os.environ, WINEDEBUG="-all"))
        if r.returncode != 0:
            sys.exit("%s: %s%s" % (src, r.stdout, r.stderr))
        data = open(b, "rb").read()
        asm = open(a).read()
        major = {"vs_3_0": 0xFFFE0300, "ps_3_0": 0xFFFF0300}[prof]
        assert int.from_bytes(data[:4], "little") == major, src
        assert int.from_bytes(data[-4:], "little") == 0x0000FFFF, src
        ninst = sum(1 for l in asm.splitlines() if l and not l.startswith(("vs_", "ps_", "dcl", "def", "//")))
        out.append("/* %s %s, %d bytes, %d instructions, sha256 %s */" %
                   (src, prof, len(data), ninst, hashlib.sha256(data).hexdigest()[:16]))
        words = [int.from_bytes(data[i:i+4], "little") for i in range(0, len(data), 4)]
        out.append("static const unsigned long %s[%d] =\n{" % (sym, len(words)))
        for i in range(0, len(words), 8):
            out.append("    " + ", ".join("0x%08Xu" % w for w in words[i:i+8]) + ",")
        out.append("};\n")
        print("%-24s %s %5d bytes %4d instr" % (src, prof, len(data), ninst))
    open(OUT, "w", newline="\n").write("\n".join(out))
    print("wrote", OUT)

if __name__ == "__main__":
    main()
